const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const base = process.env.ASSIGNMENT_TEST_URL || 'http://127.0.0.1:5199'
async function run() {
  const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } })
    await page.clock.setFixedTime(new Date('2026-11-09T15:00:00Z'))
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.route(/https:\/\/fonts\.(googleapis|gstatic)\.com\//, route => route.abort())
    await page.goto(`${base}/tests/assigned-workers.html`)
    const panel = page.getByRole('region', { name: 'Assigned workers', exact: true })
    await panel.getByText('3/3 slots covered', { exact: true }).waitFor()
    const revision = page.getByRole('combobox', { name: 'Viewing revision', exact: true })
    assert.equal(await revision.inputValue(), 'revision-2', 'Explicit revision links stay selected')
    assert.deepEqual(await revision.locator('option').allTextContents(), [
      'Revision 4 · Saved · not posted', 'Revision 3 · Upcoming', 'Revision 2 · Current',
    ])
    assert.equal(await page.getByRole('heading', { name: /Weekly care (need|request) history/ }).count(), 0)
    assert.match(await panel.innerText(), /Revision 2/)
    const friday = panel.getByRole('article', { name: 'Friday 09:00–14:00' })
    assert.match(await friday.innerText(), /Jordan Demo/)
    assert.match(await friday.innerText(), /Morgan Demo/)
    assert.match(await friday.innerText(), /Nov 12, 2026/)
    assert.equal(await panel.getByRole('button', { name: /Manage assignment/ }).count(), 0, 'API forbids ending a revision that already ends')
    const summary = panel.locator('summary')
    await summary.focus(); await page.keyboard.press('Enter')
    assert.equal(await panel.locator('details').getAttribute('open'), '')
    assert.match(await panel.locator('details').innerText(), /Scheduled change/)
    assert.match(await panel.locator('details').innerText(), /Morgan taking over Friday coverage/)
    if (process.env.ASSIGNMENT_SCREENSHOT_DIR) await panel.screenshot({ path: `${process.env.ASSIGNMENT_SCREENSHOT_DIR}/assigned-workers-implemented.png` })
    await revision.selectOption('revision-4')
    await panel.getByText('Proposed · Not scheduled', { exact: true }).waitFor()
    assert.doesNotMatch(await panel.innerText(), /Alex Demo|Jordan Demo|Morgan Demo/)
    await revision.selectOption('revision-3')
    await panel.getByText('2/2 slots covered', { exact: true }).waitFor()
    assert.equal(await panel.locator('details').getAttribute('open'), null, 'History resets for the selected revision')
    if (process.env.ASSIGNMENT_SCREENSHOT_DIR) await panel.screenshot({ path: `${process.env.ASSIGNMENT_SCREENSHOT_DIR}/assigned-workers-manage.png` })
    await panel.getByRole('button', { name: /Manage assignment for Alex Demo/ }).first().click()
    const dialog = page.getByRole('dialog')
    assert.equal(await dialog.getByRole('checkbox').count(), 2)
    await dialog.getByRole('checkbox', { name: /Fri/ }).check()
    await dialog.getByLabel('Stop visits from', { exact: false }).fill('2026-11-30')
    await dialog.getByLabel('Reason for the assignment history').fill('Friday replacement needed')
    await dialog.getByRole('button', { name: 'Review change' }).click()
    assert.doesNotMatch(await dialog.locator('ul').innerText(), /Mon/)
    await page.evaluate(() => { window.assignedWorkersFixture.stale = true })
    await dialog.getByRole('button', { name: 'Confirm and end selected slots' }).click()
    await dialog.getByText('The assignment changed. Review again.').waitFor()
    await page.evaluate(() => { window.assignedWorkersFixture.stale = false })
    await dialog.getByRole('button', { name: 'Review change' }).click()
    await dialog.getByRole('button', { name: 'Confirm and end selected slots' }).click()
    await panel.getByRole('link', { name: 'Find replacement coverage' }).waitFor()
    const fixture = await page.evaluate(() => window.assignedWorkersFixture)
    assert.deepEqual(fixture.posts.map(p => p.assignment_ids), [['next-alex-friday']])
    assert.equal(fixture.rows.find(a => a.id === 'next-alex').stops_from, null)
    await panel.locator('summary').click()
    assert.match(await panel.locator('details').innerText(), /Friday replacement needed/)
    await page.evaluate(() => { window.assignedWorkersFixture.fail = true; void window.refreshAssignedWorkers() })
    await panel.getByRole('alert').waitFor()
    assert.equal(await panel.locator('.aw-grid').count(), 0, 'Failed query never appears as all clear')
    await page.evaluate(() => { window.assignedWorkersFixture.fail = false })
    await panel.getByRole('button', { name: 'Retry', exact: true }).click()
    await panel.locator('.aw-grid').waitFor()
    await revision.selectOption('revision-2')
    await panel.getByText('3/3 slots covered', { exact: true }).waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    await revision.scrollIntoViewIfNeeded()
    const pickerBox = await revision.boundingBox()
    assert.ok(pickerBox.x >= 0 && pickerBox.x + pickerBox.width <= 391, 'Revision dropdown fits mobile viewport')
    await panel.scrollIntoViewIfNeeded()
    for (const card of await panel.getByRole('article').all()) {
      const box = await card.boundingBox()
      assert.ok(box.x >= 0 && box.x + box.width <= 391, 'Slot card fits mobile viewport')
    }
    if (process.env.ASSIGNMENT_SCREENSHOT_DIR) await panel.screenshot({ path: `${process.env.ASSIGNMENT_SCREENSHOT_DIR}/assigned-workers-mobile.png` })
    assert.deepEqual(errors, [])
    console.log('Assigned workers passed: revision selection, replacements, keyboard history, scoped management, stale retry, failure recovery and mobile layout.')
  } finally { await browser.close() }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
