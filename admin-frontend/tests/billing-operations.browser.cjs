const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
const screenshotDir = process.env.BILLING_OPERATIONS_SCREENSHOT_DIR
if (screenshotDir) fs.mkdirSync(screenshotDir, { recursive: true })
const base = process.env.BILLING_OPERATIONS_TEST_URL || 'http://127.0.0.1:5208'
async function run() {
  const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    // Keep the verification isolated from hosted accounts and services.
    await page.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort())
    await page.goto(`${base}/tests/billing-operations.html`)
    await page.getByText('No pending or failed messages.', { exact: true }).waitFor()
    await page.getByText('No open billing questions.', { exact: true }).waitFor()
    if (screenshotDir) await page.screenshot({ path: path.join(screenshotDir, 'billing-operations-desktop.png'), fullPage: true })
    await page.getByLabel('Agency name', { exact: true }).fill('Unknown')
    await page.getByRole('button', { name: 'Search', exact: true }).click()
    await page.getByText('No agencies match your search.').waitFor()
    await page.getByRole('button', { name: 'Clear search' }).click()
    await page.getByRole('button', { name: 'Open billing for Sunrise Home Care' }).click()
    await page.getByRole('heading', { name: 'Sunrise Home Care', exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Recheck Stripe history', exact: true }).isDisabled(), true)
    await page.getByRole('button', { name: 'Reserve founding offer', exact: true }).click()
    await page.getByRole('group', { name: 'Confirm agency action' }).waitFor()
    assert.equal(await page.evaluate(() => window.billingOperationsFixture.calls.filter(call => call.method === 'post').length), 0)
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    assert.equal(await page.getByRole('group', { name: 'Confirm agency action' }).count(), 0)
    await page.getByRole('button', { name: 'Back to agencies' }).click()
    assert.equal(await page.evaluate(() => document.activeElement.id), 'agency-directory')
    await page.evaluate(() => { window.billingOperationsFixture.failures = ['/webhooks', '/review-requests', '/organizations'] })
    await page.getByRole('button', { name: 'Refresh message status' }).click()
    await page.getByText('Could not load Stripe message status. Refresh to retry.').waitFor()
    assert.equal(await page.getByText('No pending or failed messages.', { exact: true }).count(), 0)
    await page.getByRole('button', { name: 'Refresh questions' }).click()
    await page.getByText('Could not load billing questions. Refresh to retry.').waitFor()
    assert.equal(await page.getByText('No open billing questions.', { exact: true }).count(), 0)
    await page.getByRole('button', { name: 'Refresh agencies' }).click()
    await page.getByText('Could not load agencies. Refresh to retry.').waitFor()
    assert.equal(await page.getByRole('button', { name: 'Open billing for Sunrise Home Care' }).count(), 0)
    await page.goto(`${base}/tests/billing-operations.html?populated`)
    await page.getByRole('button', { name: 'Load more agencies' }).click()
    await page.getByRole('button', { name: 'Open billing for Maple Home Support' }).waitFor()
    await page.getByRole('button', { name: 'Open agency billing' }).click()
    await page.getByRole('heading', { name: 'Maple Home Support', exact: true, level: 2 }).waitFor()
    await page.getByRole('button', { name: 'Back to agencies' }).click()
    await page.getByRole('button', { name: 'Record review response' }).click()
    await page.getByLabel('Response visible to the agency').fill('Reviewed the September client count. No adjustment is needed.')
    await page.getByRole('button', { name: 'Save response and resolve' }).click()
    await page.getByText('No open billing questions.', { exact: true }).waitFor()
    for (const width of [390, 768, 1024]) {
      await page.setViewportSize({ width, height: 900 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, `Overflow at ${width}px`)
    }
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto(`${base}/tests/billing-operations.html?populated`)
    await page.getByText('evt_fictional_payment').waitFor()
    if (screenshotDir) await page.screenshot({ path: path.join(screenshotDir, 'billing-operations-mobile.png'), fullPage: true })
    await page.getByRole('button', { name: 'Open agency billing' }).click()
    await page.getByRole('heading', { name: 'Maple Home Support', exact: true, level: 2 }).waitFor()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'Detail overflow')
    if (screenshotDir) await page.screenshot({ path: path.join(screenshotDir, 'billing-operations-detail-mobile.png'), fullPage: true })
    assert.deepEqual(errors, [])
    console.log('PASS: search/clear, paging, selection/focus, confirmation/cancel, permission gating, question response, refresh errors, and responsive layouts.')
  } finally { await browser.close() }
}
run().catch(error => { console.error(error); process.exitCode = 1 })


