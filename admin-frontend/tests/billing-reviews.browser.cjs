const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const base = process.env.BILLING_REVIEW_TEST_URL || 'http://127.0.0.1:5201'
async function run() {
  const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 950 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.route(/https:\/\/fonts\.(googleapis|gstatic)\.com\//, route => route.abort())
    await page.goto(`${base}/tests/billing-reviews.html`)
    await page.getByRole('heading', { name: 'Report a billing mistake' }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Submit for review' }).isDisabled(), true)
    await page.getByRole('textbox', { name: 'Billing question', exact: true }).fill('Please review the count: a fictional client had only cancelled visits.')
    await page.evaluate(() => { window.billingReviewFixture.fail = true })
    await page.getByRole('button', { name: 'Submit for review' }).click()
    await page.getByRole('alert').first().waitFor()
    assert.match(await page.getByRole('textbox', { name: 'Billing question', exact: true }).inputValue(), /cancelled/)
    await page.evaluate(() => { window.billingReviewFixture.fail = false })
    await page.getByRole('button', { name: 'Submit for review' }).click()
    await page.getByText('Your request has been recorded for Care Harbor to review.').waitFor()
    const posts = await page.evaluate(() => window.billingReviewFixture.calls.filter(call => call.method === 'post'))
    assert.equal(posts[0].body.request_id, posts[1].body.request_id)
    await page.getByRole('button', { name: 'Refresh questions' }).click()
    await page.getByRole('button', { name: 'Open agency billing' }).click()
    assert.equal(await page.evaluate(() => window.billingReviewFixture.selected), 'org-fictional')
    await page.getByRole('button', { name: 'Record review response' }).click()
    await page.getByLabel('Response visible to the agency').fill('Reviewed and confirmed that the cancelled-only client was excluded. No charge adjustment is needed.')
    await page.getByRole('button', { name: 'Save response and resolve' }).click()
    await page.getByText('No open billing questions.').waitFor()
    await page.getByRole('button', { name: 'Refresh review responses' }).click()
    await page.getByText(/Care Harbor:.*Reviewed and confirmed/).waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
    assert.deepEqual(errors, [])
    console.log('PASS: report failure/retry, retained request ID, operator review, agency response, mobile layout')
  } finally { await browser.close() }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
