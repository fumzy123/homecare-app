// Uses only the development fixture host; no agency credentials or network mutations.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const base = process.env.ASSIGNMENT_TEST_URL || 'http://127.0.0.1:5199'
async function run() {
  const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } })
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.route(/https:\/\/fonts\.(googleapis|gstatic)\.com\//, r => r.abort())
    await page.goto(`${base}/tests/assignments.html`)
    await page.getByRole('heading', { name: 'Margaret Example' }).waitFor()
    await page.getByRole('button', { name: 'Manage assignment' }).click()
    const dialog = page.getByRole('dialog')
    assert.equal(await dialog.getByRole('button', { name: 'Review change' }).isDisabled(), true)
    await dialog.getByRole('checkbox', { name: /Fri/ }).check()
    await dialog.getByLabel('Stop visits from').fill('2026-10-16')
    await dialog.getByLabel('Reason for the assignment history').fill('Reassigned to another client')
    await dialog.getByRole('button', { name: 'Review change' }).click()
    await dialog.getByRole('heading', { name: 'Confirm assignment change' }).waitFor()
    assert.match(await dialog.innerText(), /Past visits and progress notes stay on file/)
    assert.doesNotMatch(await dialog.locator('ul').innerText(), /Mon|Wed/)
    // Stale confirmation keeps the dialog open and requires another review.
    await page.evaluate(() => { window.assignmentFixture.fail = true })
    await dialog.getByRole('button', { name: 'Confirm and end selected slots' }).click()
    await dialog.getByRole('alert').waitFor()
    assert.match(await dialog.getByRole('alert').innerText(), /Review again/)
    await page.evaluate(() => { window.assignmentFixture.fail = false })
    await dialog.getByRole('button', { name: 'Review change' }).click()
    await dialog.getByRole('button', { name: 'Confirm and end selected slots' }).click()
    await page.getByRole('link', { name: 'Find replacement coverage' }).waitFor()
    const fixture = await page.evaluate(() => window.assignmentFixture)
    assert.deepEqual(fixture.posts.at(-1).assignment_ids, ['assignment-2'])
    assert.equal(fixture.rows.filter(a => a.can_end).length, 2)
    await page.getByRole('checkbox', { name: 'Show ended assignments' }).check()
    assert.match(await page.getByRole('region', { name: 'Assignments' }).innerText(), /Reassigned to another client/)
    await page.getByRole('link', { name: 'Client care', exact: true }).click()
    await page.getByRole('heading', { name: 'Blue Example' }).waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: 'Manage assignment' }).click()
    await dialog.waitFor()
    const bounds = await dialog.boundingBox()
    assert.ok(bounds.x >= 0 && bounds.width <= 390)
    await page.keyboard.press('Escape')
    await dialog.waitFor({ state: 'hidden' })
    assert.deepEqual(errors, [])
    console.log('Assignment UI passed: both entry points, partial selection, review, stale failure, history, responsive dialog and Escape.')
  } finally { await browser.close() }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
